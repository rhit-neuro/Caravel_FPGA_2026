"""Generate rtl/fp_exp2_rom.v -- the lookup table used by fp_exp.v.

The table holds 2^(i/128) for i = 0..127. Each value is between 1.0 and 2.0
and is stored as a whole number equal to value * 2^30 (fixed point, see the
"FIXED POINT" note at the top of fp_exp.v).

Run from the FP32_Sims folder:   python3 scripts/gen_exp_rom.py
"""
import os

# =============================================================================
# Where to write the Verilog file: <this script's folder>/../rtl/fp_exp2_rom.v
# (same as C: snprintf(path, ..., "%s/../rtl/fp_exp2_rom.v", script_dir))
# =============================================================================
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rtl", "fp_exp2_rom.v")

# =============================================================================
# Build the file one text line at a time in a Python list (like an array of
# strings in C), then write them all out at the end.
# =============================================================================

# ---- file header + module ports (copied into the .v file word for word)
lines = [
    "`timescale 1ns/1ps",
    "// =============================================================================",
    "// fp_exp2_rom.v  --  GENERATED by scripts/gen_exp_rom.py, do not edit by hand",
    "// =============================================================================",
    "// A read-only lookup table (ROM). In C this would be:",
    "//     const uint32_t table[128] = { 2^(0/128)*2^30, 2^(1/128)*2^30, ... };",
    "//     val = table[idx];",
    "// Vivado builds this out of LUTs (it is small), not BRAM.",
    "module fp_exp2_rom (",
    "    input  wire [6:0]  idx,   // which entry, 0..127",
    "    output reg  [30:0] val    // 2^(idx/128), scaled by 2^30",
    ");",
    "    // 'always @(*)' = combinational logic: val updates instantly when idx changes",
    "    always @(*) begin",
    "        case (idx)   // like a C switch statement",
]

# ---- one 'case' line per table entry
for i in range(128):                              # for (i = 0; i < 128; i++)
    v = round(2 ** (i / 128) * 2 ** 30)           # 2^(i/128) as a fixed-point integer (x 2^30)
    # e.g. "7'd5  : val = 31'd1103211687;   // 2^(5/128) = 1.027445949"
    lines.append(f"            7'd{i:<3}: val = 31'd{v};   // 2^({i}/128) = {2 ** (i / 128):.9f}")

# ---- close the switch, the always block and the module
lines += [
    "            default: val = 31'd0;",
    "        endcase",
    "    end",
    "endmodule",
    "",
]

# =============================================================================
# Write everything to disk ("w" = overwrite, like fopen(OUT, "w") in C)
# =============================================================================
with open(OUT, "w") as f:
    f.write("\n".join(lines))                     # join with newlines = one line per entry
print("wrote", os.path.normpath(OUT))
